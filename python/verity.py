# Recalibration thresholds
truth_df = df[df["label"] == 0]
THRESHOLDS = {
    "denial_ratio": (
        "high",
        truth_df["denial_ratio"].mean() + 1.2 * truth_df["denial_ratio"].std(),
        2.0,
    ),
    "repetition_ratio": (
        "high",
        truth_df["repetition_ratio"].mean() + 1.2 * truth_df["repetition_ratio"].std(),
        1.5,
    ),
    "n_exclamations": ("high", 1.5, 1.5),
    "specificity_score": (
        "low",
        truth_df["specificity_score"].mean() - 0.8 * truth_df["specificity_score"].std(),
        1.5,
    ),
    "hedge_ratio": (
        "low",
        truth_df["hedge_ratio"].mean() - 0.5 * truth_df["hedge_ratio"].std(),
        1.2,
    ),
    "first_person_ratio": (
        "high",
        truth_df["first_person_ratio"].mean() + 1.5 * truth_df["first_person_ratio"].std(),
        1.0,
    ),
    "avg_sentence_len": (
        "low",
        truth_df["avg_sentence_len"].mean() - 1.0 * truth_df["avg_sentence_len"].std(),
        0.8,
    ),
}


def recalibrated_score(feats):
    feat_vec = np.array([[feats[c] for c in FEATURE_COLS]])
    rf_prob = rf.predict_proba(feat_vec)[0]
    rule_score = 0.0
    total_weight = 0.0
    for feat, (direction, threshold, weight) in THRESHOLDS.items():
        val = feats.get(feat, 0)
        if (direction == "high" and val > threshold) or (direction == "low" and val < threshold):
            rule_score += weight
        total_weight += weight
    rule_decep = rule_score / total_weight if total_weight > 0 else 0.5
    blended_decep = 0.55 * rf_prob[1] + 0.45 * rule_decep
    if blended_decep > 0.58:
        blended_decep = min(0.97, blended_decep * 1.25)
    elif blended_decep < 0.42:
        blended_decep = max(0.03, blended_decep * 0.75)
    blended_truth = 1.0 - blended_decep
    pred = 1 if blended_decep >= 0.5 else 0
    return pred, np.array([blended_truth, blended_decep]), feats


