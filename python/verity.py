def get_followup(pred, category):
    pool = FOLLOWUP_POOL["deceptive" if pred == 1 else "truthful"]
    return random.choice(pool.get(category, pool["WORKPLACE"]))


def get_signals(feats, pred):
    signals = []
    if feats["n_exclamations"] > 1:
        signals.append(
            ("⚠", f"High exclamation count ({feats['n_exclamations']}) — emotional overstatement")
        )
    if feats["denial_count"] > 3:
        signals.append(
            ("⚠", f"Over-denial pattern ({feats['denial_count']} denials) — defensive response")
        )
    if feats["repetition_ratio"] > 0.15:
        signals.append(
            (
                "⚠",
                f"High word repetition ({feats['repetition_ratio']:.2f}) — cognitive stress signal",
            )
        )
    if feats["specificity_score"] < 0.25:
        signals.append(
            (
                "⚠",
                f"Vague response (specificity {feats['specificity_score']:.2f}) — lacks concrete detail",
            )
        )
    if feats["first_person_ratio"] > 0.25:
        signals.append(
            (
                "⚠",
                f"Excessive self-reference ({feats['first_person_ratio']:.2f}) — over-justification",
            )
        )
    if feats["hedge_count"] >= 2:
        signals.append(
            ("✓", f"Natural hedging ({feats['hedge_count']} hedges) — honest uncertainty pattern")
        )
    if feats["specificity_score"] > 0.45:
        signals.append(
            ("✓", f"High specificity ({feats['specificity_score']:.2f}) — concrete truthful detail")
        )
    if 0.05 < feats["first_person_ratio"] < 0.20:
        signals.append(("✓", "Balanced first-person usage — natural personal account"))
    if feats["denial_count"] <= 1 and feats["n_exclamations"] == 0:
        signals.append(("✓", "Calm delivery — no defensive linguistic markers detected"))
    if not signals:
        signals.append(("—", "No strong indicators detected in this response"))
    return signals


