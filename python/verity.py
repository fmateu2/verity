def render_result(pred, truth_pct, decep_pct, signals, turn_num):
    is_decep = pred == 1

    # Verdict panel
    if is_decep:
        verdict_text = Text("  🔴  DECEPTIVE  ", style="bold white on red")
        pct_text = Text(f"  Deception probability: {decep_pct:.1f}%  ", style="bold red")
        border = "red"
    else:
        verdict_text = Text("  🟢  TRUTHFUL  ", style="bold white on green")
        pct_text = Text(f"  Credibility score: {truth_pct:.1f}%  ", style="bold green")
        border = "green"

    # Risk bar
    bar_len = 36
    decep_fill = int(decep_pct / 100 * bar_len)
    truth_fill = bar_len - decep_fill
    bar = Text()
    bar.append("  RISK  [", style="dim white")
    bar.append("█" * decep_fill, style="bold red")
    bar.append("░" * truth_fill, style="dim green")
    bar.append("]", style="dim white")
    bar.append(f"  {decep_pct:.1f}%", style="bold red" if is_decep else "bold green")

    # Signals table
    sig_table = Table(box=box.SIMPLE, show_header=False, padding=(0, 1))
    sig_table.add_column("icon", style="bold", width=3)
    sig_table.add_column("signal", style="white")
    for icon_s, msg in signals[:4]:
        color = "red" if icon_s == "⚠" else "green"
        sig_table.add_row(f"[{color}]{icon_s}[/{color}]", msg)

    content = Text()
    content.append_text(verdict_text)
    content.append("\n")
    content.append_text(pct_text)

    console.print(
        Panel(
            content,
            title=f"[bold white] TURN {turn_num} RESULT [/bold white]",
            border_style=border,
            padding=(0, 2),
        )
    )
    console.print(bar)
    console.print()
    console.print(
        Panel(
            sig_table,
            title="[bold white] SIGNAL ANALYSIS [/bold white]",
            border_style="dim white",
            padding=(0, 1),
        )
    )
    console.print()


