def extract_text_features(text):
    tl = text.lower()
    words = tl.split()
    sentences = [s.strip() for s in re.split(r'[.!?]+', text) if s.strip()]
    n_words = len(words)

    hedge_count = sum(1 for h in HEDGES if h in tl)
    intens_count = sum(1 for i in INTENSIFIERS if i in tl)
    denial_count = sum(1 for d in DENIALS if d in tl)
    dist_count = sum(1 for d in DISTANCERS if d in tl)
    fp_count = tl.count(" i ") + tl.count("i ") + tl.count(" my ") + tl.count(" me ")
    pos = sum(
        1
        for w in [
            "great",
            "good",
            "excellent",
            "nice",
            "wonderful",
            "clean",
            "comfortable",
            "friendly",
            "helpful",
            "fine",
            "okay",
            "alright",
        ]
        if w in tl
    )
    neg = sum(
        1
        for w in [
            "bad",
            "poor",
            "terrible",
            "awful",
            "dirty",
            "rude",
            "noisy",
            "disappointing",
            "wrong",
            "problem",
            "issue",
        ]
        if w in tl
    )

    return {
        "n_words": n_words,
        "n_sentences": max(len(sentences), 1),
        "avg_word_len": round(float(np.mean([len(w) for w in words])) if words else 0, 3),
        "avg_sentence_len": round(n_words / max(len(sentences), 1), 3),
        "hedge_count": hedge_count,
        "hedge_ratio": round(hedge_count / n_words if n_words else 0, 4),
        "denial_count": denial_count,
        "denial_ratio": round(denial_count / n_words if n_words else 0, 4),
        "distancing_ratio": round(dist_count / n_words if n_words else 0, 4),
        "first_person_ratio": round(fp_count / n_words if n_words else 0, 4),
        "n_questions": text.count('?'),
        "n_exclamations": text.count('!'),
        "repetition_ratio": round(1 - (len(set(words)) / len(words)) if words else 0, 4),
        "specificity_score": round(max(0, (hedge_count - intens_count + 3) / 6), 4),
        "sentiment_ratio": round((pos - neg) / (pos + neg + 1), 4),
    }


def pressure_level(text):
    t = text.lower()
    if any(w in t for w in ["stole", "fraud", "scam", "cheated", "lied", "steal", "crime"]):
        return 4
    if any(w in t for w in ["complaint", "manager", "issue", "problem", "billing", "incident"]):
        return 3
    if any(w in t for w in ["business", "conference", "meeting", "work", "office", "project"]):
        return 2
    return 1


